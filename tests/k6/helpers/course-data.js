import http from 'k6/http';
import { check } from 'k6';
import { apiUrl, requestParams, uniqueSuffix } from './config.js';
import { pick, safeJson } from './checks.js';

export function createCourse(token, label = 'course', metricName = 'Setup_Create_Course', extraTags = {}) {
  const suffix = uniqueSuffix(label);
  const response = http.post(
    apiUrl('/api/courses'),
    JSON.stringify({
      title: `k6 ${label} ${suffix}`,
      theme: 'Performance testing',
      description: `Course generated by k6 scenario ${label}.`,
    }),
    requestParams(metricName, token, {
      endpoint: '/api/courses',
      phase: metricName.startsWith('Setup') ? 'setup' : 'default',
      ...extraTags,
    }),
  );

  const body = safeJson(response);
  const courseId = pick(body, 'id', 'Id');

  check(response, {
    [`${metricName}: status is 201`]: (r) => r.status === 201,
    [`${metricName}: course id returned`]: () => Boolean(courseId),
  });

  return {
    response,
    body,
    courseId,
  };
}

