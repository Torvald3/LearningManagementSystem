export function createCourseFixture(token, label = 'fixture') {
  const course = createCourse(token, label);

  if (!course.courseId) {
    throw new Error(`Could not create setup course. Status: ${course.response.status}`);
  }

  const module = createCourseModule(token, course.courseId, label);

  if (!module.moduleId) {
    throw new Error(`Could not create setup course module. Status: ${module.response.status}`);
  }

  const lesson = createLesson(token, course.courseId, module.moduleId, label);

  if (!lesson.lessonId) {
    throw new Error(`Could not create setup lesson. Status: ${lesson.response.status}`);
  }

  return {
    courseId: course.courseId,
    moduleId: module.moduleId,
    lessonId: lesson.lessonId,
  };
}
